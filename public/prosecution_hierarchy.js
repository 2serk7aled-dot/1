    function getUserAccessibleEvidences(user = currentUser) {
      if (!user || user.role === 'admin') {
        return evidences;
      }

      return evidences.filter(e => {
        const uAppeal = user.appealProsecution;
        const uTotal = user.totalProsecution;
        const uPartial = user.partialProsecution;

        const isSpecificPartial = uPartial && 
          uPartial !== 'كافة النيابات' && 
          uPartial !== 'كافة النيابات الجزئية التابعة للنيابة الكلية' &&
          uPartial !== 'الكل / كافة النيابات الجزئية التابعة للكلية';

        if (isSpecificPartial) {
          return e.partialProsecution === uPartial;
        }

        if (uTotal && uTotal !== 'كافة النيابات' && uTotal !== 'كافة النيابات الكلية') {
          return e.totalProsecution === uTotal;
        }

        if (uAppeal && uAppeal !== 'كافة النيابات (مدير عام)' && uAppeal !== 'كافة الاستئنافات (نطاق مركزي عام)') {
          return e.appealProsecution === uAppeal;
        }

        return true;
      });
    }

