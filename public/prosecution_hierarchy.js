        userPartial !== 'الكل / كافة النيابات الجزئية التابعة للكلية';

      if (isSpecificPartial) {
        // Strict partial isolation
        appealSel.innerHTML = `<option value="${escapeHtml(userAppeal)}">${escapeHtml(userAppeal)}</option>`;
        appealSel.value = userAppeal;
        appealSel.disabled = true;

        totalSel.innerHTML = `<option value="${escapeHtml(userTotal)}">${escapeHtml(userTotal)}</option>`;
        totalSel.value = userTotal;
        totalSel.disabled = true;

        partialSel.innerHTML = `<option value="${escapeHtml(userPartial)}">${escapeHtml(userPartial)}</option>`;
        partialSel.value = userPartial;
        partialSel.disabled = true;

        const customCont = document.getElementById('newCustomPartialContainer');
        if (customCont) customCont.style.display = 'none';

        if (noticeContainer) {
          noticeContainer.style.display = 'flex';
          noticeContainer.innerHTML = `
            <i class="fa-solid fa-lock" style="color: #2563eb; font-size: 15px;"></i>
            <span>التبعية القضائية مقيدة بصلاحية حسابك فقط: <strong>${escapeHtml(userPartial)}</strong> (التابعة لـ ${escapeHtml(userTotal || '')} / ${escapeHtml(userAppeal)})</span>
          `;
        }
      } else if (userTotal && userTotal !== 'كافة النيابات' && userTotal !== 'كافة النيابات الكلية') {
        // Total prosecution level: user can select any partial belonging to this total
        appealSel.innerHTML = `<option value="${escapeHtml(userAppeal)}">${escapeHtml(userAppeal)}</option>`;
        appealSel.value = userAppeal;
        appealSel.disabled = true;

        totalSel.innerHTML = `<option value="${escapeHtml(userTotal)}">${escapeHtml(userTotal)}</option>`;
        totalSel.value = userTotal;
        totalSel.disabled = true;

        const totalsObj = PROSECUTION_HIERARCHY[userAppeal] || {};
        const partialsList = totalsObj[userTotal] || ['أخرى / مخصص'];
        partialSel.innerHTML = partialsList.map(p => `<option value="${p}">${p}</option>`).join('');
        partialSel.disabled = false;
        handleNewPartialProsecutionChange();

        if (noticeContainer) {
          noticeContainer.style.display = 'flex';
          noticeContainer.innerHTML = `
            <i class="fa-solid fa-building-columns" style="color: #2563eb; font-size: 15px;"></i>
            <span>أنت مسجل على نطاق النيابة الكلية: <strong>${escapeHtml(userTotal)}</strong>. يمكنك قيد الأحراز بأي من النيابات الجزئية التابعة لك في القائمة أدناه.</span>
          `;
        }
      } else {
        appealSel.disabled = false;
        totalSel.disabled = false;
        partialSel.disabled = false;
        if (noticeContainer) noticeContainer.style.display = 'none';
        populateAppealDropdowns();
      }
